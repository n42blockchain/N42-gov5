// Vector V7 of the mixed production standard (Profile 1): the leader
// schedule. A15 leader(v) = (v / T) mod n, A18 epochs, and SYNC §10.2
// view_after_tc with the epoch-boundary clamp (A22, active from view 0 on
// Profile 1; AM32), computed by gov5's consensus functions
// (hotstuff.LeaderForViewWithTenure, hotstuff.ViewAfterTimeout,
// EpochManager). SYNC §10.4 is reproduced without S6 (switch off) and S8
// (activation view), which Profile 1 does not have.
//
// The AM33 vector (timeout backoff, v1.2) is generated by
// TestProfile1VectorAM33 below from gov5's Pacemaker and RoundState.
//
// N42_PROFILE1_VECTORS_UPDATE=1 rewrites testdata/profile1/vectors/{V7,AM33};
// N42_PROFILE1_VECTORS_MIRROR=<dir> also writes the files to <dir>/{V7,AM33}.

