func am33Pacemaker(base, max uint64, n int) *hotstuff.Pacemaker {
	p := hotstuff.NewPacemaker(base, max)
	if n > 0 {
		p.SetCommitteeSize(n)
	}
	return p
}

// am33Walk runs views from start with the given leaders silent until the
// first view whose leader is live (its QC ends the run). Each view's timer
// is the pacemaker's timeout for the RoundState's consecutive-timeout count
// on entering it; a TC increments the count (RoundState.Timeout) and moves
// to view_after_tc. n = 0 for the pacemaker means the previous rule (g = 1).
func am33Walk(n, pmN int, tenure, e, base, max uint64, dead map[uint32]bool, start uint64) ([]am33Step, uint64) {
	pm := am33Pacemaker(base, max, pmN)
	rs := hotstuff.NewRoundState()
	var steps []am33Step
	var gap uint64
	for v := start; ; {
		l := v7Leader(v, n, tenure)
		c := rs.ConsecutiveTimeouts()
		to := uint64(pm.TimeoutDuration(c).Milliseconds())
		if !dead[l] {
			steps = append(steps, am33Step{View: v, Leader: l, C: c, TimeoutMs: to, Event: "QC", NextView: v + 1})
			return steps, gap
		}
		rs.Timeout()
		next := v7After(v, tenure, e, true)
		steps = append(steps, am33Step{View: v, Leader: l, C: c, TimeoutMs: to, Event: "TC", NextView: next})
		gap += to
		v = next
	}
}

// TestProfile1VectorAM33 generates and checks the AM33 timeout-backoff vector.
func TestProfile1VectorAM33(t *testing.T) {
	std, _ := v7Profile1(t, filepath.Join(profile1Dir, profile1StandardFile), "standard")
	out := am33File{
		Vector:   "AM33",
		Standard: "N42 mixed production standard, amendment AM33 (consecutive absent leaders, v1.2): timeout backoff grows once per g TCs",
		Rules: []string{
			"timeout(c) = min(base_eff * 2^floor(c / g), max), g = min(f + 1, 3), f = floor((n - 1) / 3), n = the validator-set size.",
			"c increments on each local view timeout; it resets to 0 on a commit QC (Decide) and on a QC-based view jump; a TC, including one adopted from SyncInfo, never resets it.",
			"A view's timer is timeout(c) with c as it stands on entering the view.",
			"base_eff is the local adaptive base max(base, 2 * p95 commit latency) capped at max; these vectors have no latency samples, so base_eff = base.",
		},
		Notes: []string{
			"Generated by gov5 TestProfile1VectorAM33 (internal/profile1_v7_test.go) from hotstuff.Pacemaker (TimeoutDuration, SetCommitteeSize), hotstuff.BackoffGroupSize, hotstuff.RoundState and hotstuff.ViewAfterTimeout.",
			"previousRule* columns are the same code with no committee size (g = 1): the rule before AM33.",
			"runs: the leaders listed are silent; every other leader forms a QC within its view. gapMs = sum of the timeouts of the TC views (the time from entering the first dead view to entering the live view).",
		},
	}
	for _, n := range []int{1, 2, 3, 4, 5, 6, 7, 10, 100, 512} {
		out.Groups = append(out.Groups, am33Group{N: n, F: (n - 1) / 3, G: hotstuff.BackoffGroupSize(n)})
	}
	type bm struct{ base, max uint64 }
	params := []bm{{24000, 96000}, {std.BaseTimeoutMs, std.MaxTimeoutMs}}
	for _, p := range params {
		for _, n := range []int{4, 7, 100} {
			cur, prev := am33Pacemaker(p.base, p.max, n), am33Pacemaker(p.base, p.max, 0)
			tab := am33Table{N: n, G: hotstuff.BackoffGroupSize(n), BaseMs: p.base, MaxMs: p.max}
			for c := uint32(0); c <= 12; c++ {
				tab.TimeoutsMs = append(tab.TimeoutsMs, uint64(cur.TimeoutDuration(c).Milliseconds()))
				tab.PreviousMs = append(tab.PreviousMs, uint64(prev.TimeoutDuration(c).Milliseconds()))
			}
			out.Tables = append(out.Tables, tab)
		}
	}

	run := func(id, desc string, n int, tenure, e, base, max uint64, dead []uint32, start uint64) am33Run {
		dm := map[uint32]bool{}
		for _, d := range dead {
			dm[d] = true
		}
		steps, gap := am33Walk(n, n, tenure, e, base, max, dm, start)
		_, prev := am33Walk(n, 0, tenure, e, base, max, dm, start)
		return am33Run{ID: id, Description: desc, N: n, Tenure: tenure, EpochLength: e, BaseMs: base, MaxMs: max,
			Dead: dead, StartView: start, Steps: steps, GapMs: gap, PreviousMs: prev}
	}
	deadRun := func(first uint32, k int, n int) []uint32 {
		var d []uint32
		for i := 0; i < k; i++ {
			d = append(d, uint32((int(first)+i)%n))
		}
		return d
	}
	// Gate 5d: n = 100, T = 1, six absent leaders (views 57..62).
	g5d := run("gate-5d", "gate 5d: n = 100, T = 1, E = 10800, base 24 s / max 96 s; leaders 57..62 absent", 100, 1, 10800, 24000, 96000, deadRun(57, 6, 100), 57)
	// AM33's 216 s; the previous rule's timeouts sum to 456 s (gate 5d
	// measured a 464 s block gap: the timeouts plus the block interval).
	if g5d.GapMs != 216000 || g5d.PreviousMs != 456000 {
		t.Fatalf("gate 5d gap %d ms (previous %d), want 216000 (456000)", g5d.GapMs, g5d.PreviousMs)
	}
	out.Runs = append(out.Runs, g5d)
	// Runs of k consecutive absent leaders, T = 1, no epoch boundary.
	for _, n := range []int{4, 7, 100} {
		f := (n - 1) / 3
		ks := []int{1, 2, 3, 4, 5, 6}
		if n == 100 {
			ks = append(ks, f)
		}
		for _, k := range ks {
			if k > n-1 {
				continue
			}
			out.Runs = append(out.Runs, run(fmt.Sprintf("n%d-T1-k%d", n, k), fmt.Sprintf("n = %d, T = 1, %d consecutive absent leaders (1..%d), base 24 s / max 96 s", n, k, k),
				n, 1, 0, 24000, 96000, deadRun(1, k, n), 1))
		}
	}
	// T = 8 with rotate-on-timeout: each TC skips a whole window.
	for _, n := range []int{4, 7, 100} {
		k := min(3, n-1)
		out.Runs = append(out.Runs, run(fmt.Sprintf("n%d-T8-k%d", n, k), fmt.Sprintf("n = %d, T = 8, E = 0: leaders 1..%d absent; each TC hands the next window on", n, k),
			n, 8, 0, 24000, 96000, deadRun(1, k, n), 8))
	}
	// AM32: the clamp lands on the same dead leader.
	for _, n := range []int{4, 7, 100} {
		l := v7Leader(98, n, 8)
		out.Runs = append(out.Runs, run(fmt.Sprintf("am32-n%d", n), fmt.Sprintf("AM32 clamp: n = %d, T = 8, E = 50, leader L%d of window 96..103 silent from view 98: TC(98) -> 101 (boundary, same leader), TC(101) -> 104", n, l),
			n, 8, 50, 24000, 96000, []uint32{l}, 98))
		out.Runs = append(out.Runs, run(fmt.Sprintf("am32-n%d-p1", n), fmt.Sprintf("AM32 clamp at the standard genesis timeouts (base %d ms / max %d ms), n = %d", std.BaseTimeoutMs, std.MaxTimeoutMs, n),
			n, 8, 50, std.BaseTimeoutMs, std.MaxTimeoutMs, []uint32{l}, 98))
	}
	// AM32 + a second absent leader right after the clamp: three TCs.
	for _, n := range []int{4, 7, 100} {
		l := v7Leader(98, n, 8)
		out.Runs = append(out.Runs, run(fmt.Sprintf("am32-n%d-next-dead", n), fmt.Sprintf("AM32 clamp followed by a second absent leader: n = %d, L%d and L%d silent", n, l, (l+1)%uint32(n)),
			n, 8, 50, 24000, 96000, []uint32{l, (l + 1) % uint32(n)}, 98))
	}
	for _, r := range out.Runs {
		if r.Steps[len(r.Steps)-1].Event != "QC" {
			t.Fatalf("%s: run does not end on a QC", r.ID)
		}
	}
	writeProfile1Vector(t, "AM33", "timeout_backoff.json", out)
	mirrorProfile1File(t, "AM33", "README.md")
}
