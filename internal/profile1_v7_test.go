// v7Set is a validator set of n members (only its size matters to the
// schedule).
func v7Set(n int) *hotstuff.ValidatorSet {
	return hotstuff.NewValidatorSet(make([]hotstuff.ValidatorInfo, n), uint32((n-1)/3))
}

func v7Leader(view uint64, n int, tenure uint64) uint32 {
	return uint32(hotstuff.LeaderForViewWithTenure(hotstuff.ViewNumber(view), v7Set(n), tenure))
}

func v7After(x, tenure, epoch uint64, active bool) uint64 {
	return uint64(hotstuff.ViewAfterTimeout(hotstuff.ViewNumber(x), tenure, epoch, active))
}

// v7Profile1 reads a profile-1 genesis and reports the schedule inputs gov5
// derives from it.
func v7Profile1(t *testing.T, path, label string) (v7Profile, *params.ChainConfig) {
	t.Helper()
	g, err := loadProfile1Genesis(t, path)
	if err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	cfg := g.Config
	on, from := cfg.HotStuffRotateOnTimeout()
	base, max := cfg.HotStuffTimeoutsMs()
	return v7Profile{Genesis: label, Validators: len(cfg.HotStuff.Validators), LeaderTenure: cfg.HotStuff.LeaderTenure,
		EpochLength: cfg.HotStuff.EpochLength, RotateActive: on, RotateFrom: from, BaseTimeoutMs: base, MaxTimeoutMs: max}, cfg
}

// v7Run walks views from start: a view whose leader is dead times out
// (TC, view_after_tc), any other view is certified (QC, view + 1). dead
// maps a leader index to the first view from which it is silent.
func v7Run(n int, tenure, epoch uint64, dead map[uint32]uint64, start, stop uint64) []v7Step {
	var steps []v7Step
	for v := start; v < stop; {
		l := v7Leader(v, n, tenure)
		s := v7Step{Event: "QC", View: v, Leader: l, NextView: v + 1}
		if from, ok := dead[l]; ok && v >= from {
			s.Event, s.NextView = "TC", v7After(v, tenure, epoch, true)
		}
		s.NextLeader = v7Leader(s.NextView, n, tenure)
		steps = append(steps, s)
		v = s.NextView
	}
	return steps
}

// TestProfile1VectorV7 generates and checks the V7 leader-schedule vector.
func TestProfile1VectorV7(t *testing.T) {
	std, stdCfg := v7Profile1(t, filepath.Join(profile1Dir, profile1StandardFile), "internal/testdata/profile1/standard_genesis.json")
	g8 := new(conf.Genesis)
	if err := json.Unmarshal(v1GenesisJSON(t), g8); err != nil {
		t.Fatal(err)
	}
	on8, from8 := g8.Config.HotStuffRotateOnTimeout()
	b8, m8 := g8.Config.HotStuffTimeoutsMs()
	p8 := v7Profile{Genesis: "V1/" + v1Genesis, Validators: len(g8.Config.HotStuff.Validators), LeaderTenure: g8.Config.HotStuff.LeaderTenure,
		EpochLength: g8.Config.HotStuff.EpochLength, RotateActive: on8, RotateFrom: from8, BaseTimeoutMs: b8, MaxTimeoutMs: m8}
	if !std.RotateActive || std.RotateFrom != 0 || !p8.RotateActive || p8.RotateFrom != 0 {
		t.Fatalf("profile 1 must rotate on timeout from view 0 (A22): %+v %+v", std, p8)
	}
	if !stdCfg.IsProfile1() {
		t.Fatal("standard genesis is not profile 1")
	}

	out := v7File{
		Vector:   "V7",
		Standard: "N42 mixed production standard profile 1; vector V7 (leader schedule: A15, A18, A22, SYNC §10.2/§10.4 without S6/S8, AM32)",
		Rules: []string{
			"A15: leader(v) = (v / max(T, 1)) mod n; T = config.hotstuff.leaderTenure, n = validators of the view's set.",
			"Tenure window of v: w = v / T, views w*T .. w*T + T - 1, all led by leader(v).",
			"A18: epoch(v) = (v - 1) / E for v >= 1 (view 0 is epoch 0); boundary view b: b > 1 and (b - 1) mod E = 0.",
			"A22 / SYNC §10.2: view_after_tc(x) = x + 1 if not active or T <= 1; else min(W, B) with W = (x / T + 1) * T and B = ((x - 1) / E + 1) * E + 1 (only if E > 0 and x >= 1); x + 1 if W overflows u64 or W < x + 1. Profile 1: active for every x (A = 0).",
			"A QC (or Decide) for view q moves to q + 1. A node adopts a piggybacked TC(x) only if view_after_tc(x) is above its current view.",
		},
		Profiles: []v7Profile{std, p8},
		Notes: []string{
			"Generated by gov5 TestProfile1VectorV7 (internal/profile1_v7_test.go) from hotstuff.LeaderForViewWithTenure, hotstuff.ViewAfterTimeout and hotstuff.EpochManager; profiles are read with gov5's genesis loader.",
			"viewAfterTC rows with source SYNC-10.4 are the spec table's inputs; result is gov5's.",
			"Sequences reproduce SYNC §10.4 S1-S5, S7, S9-S11 (n = 7, T = 8) and AM32's rehearsal (TC(98) -> 101 -> 104, the clamp landing on the same dead leader); S6 and S8 (switch off, activation view) do not exist on Profile 1.",
		},
	}

	// Leader tables.
	type lt struct {
		name   string
		n      int
		tenure uint64
		views  []uint64
	}
	span := func(a, b uint64) []uint64 {
		var vs []uint64
		for v := a; v <= b; v++ {
			vs = append(vs, v)
		}
		return vs
	}
	big := []uint64{1 << 32, math.MaxUint64 - 8, math.MaxUint64 - 1, math.MaxUint64}
	for _, c := range []lt{
		{"profile-1 standard genesis (n = 4, T = 8)", std.Validators, std.LeaderTenure, append(span(0, 72), 199, 200, 201, 207, 208, 1000, 1<<20)},
		{"V1 genesis_8s (n = 4, T = 1)", p8.Validators, p8.LeaderTenure, append(span(0, 12), 10799, 10800, 10801)},
		{"SYNC §10.4 (n = 7, T = 8)", 7, 8, append(span(0, 64), 96, 98, 101, 104)},
		{"n = 100, T = 1 (gate 5d)", 100, 1, append(span(55, 64), 99, 100, 101)},
		{"tenure 0 reads as 1 (n = 4)", 4, 0, span(0, 8)},
		{"large views (n = 7, T = 8)", 7, 8, big},
	} {
		tab := v7LeaderTable{Name: c.name, N: c.n, Tenure: c.tenure}
		for _, v := range c.views {
			tab.Views = append(tab.Views, v7LeaderRow{View: v, Leader: v7Leader(v, c.n, c.tenure)})
		}
		out.Leaders = append(out.Leaders, tab)
	}

	// Tenure windows.
	for _, c := range []struct {
		n      int
		tenure uint64
		views  []uint64
	}{
		{std.Validators, std.LeaderTenure, []uint64{0, 7, 8, 15, 16, 31, 32, 199, 200, 201}},
		{7, 8, []uint64{8, 11, 15, 48, 55, 56, 98}},
	} {
		for _, v := range c.views {
			w := v / c.tenure
			first, last := w*c.tenure, w*c.tenure+c.tenure-1
			l := v7Leader(v, c.n, c.tenure)
			if v7Leader(first, c.n, c.tenure) != l || v7Leader(last, c.n, c.tenure) != l || v7Leader(last+1, c.n, c.tenure) == l && c.n > 1 {
				t.Fatalf("window of view %d (n=%d T=%d) is not one leader's", v, c.n, c.tenure)
			}
			out.Windows = append(out.Windows, v7Window{N: c.n, Tenure: c.tenure, View: v, Window: w, FirstView: first, LastView: last, Leader: l})
		}
	}

	// Epochs.
	for _, c := range []struct {
		e     uint64
		views []uint64
	}{
		{std.EpochLength, []uint64{0, 1, 2, 200, 201, 202, 400, 401}},
		{p8.EpochLength, []uint64{1, 10800, 10801, 21601}},
		{10, []uint64{1, 2, 10, 11, 12, 21}},
		{50, []uint64{50, 51, 98, 101, 104}},
	} {
		em := hotstuff.NewEpochManagerWithLength(v7Set(4), c.e)
		for _, v := range c.views {
			out.Epochs = append(out.Epochs, v7Epoch{EpochLength: c.e, View: v, Epoch: em.EpochForView(v), IsBoundary: em.IsEpochBoundary(v)})
		}
	}

	// view_after_tc.
	type at struct {
		x, tenure, e uint64
		active       bool
	}
	addAfter := func(src string, rows []at) {
		for _, r := range rows {
			res := v7After(r.x, r.tenure, r.e, r.active)
			noClamp := v7After(r.x, r.tenure, 0, r.active)
			out.ViewAfter = append(out.ViewAfter, v7AfterTC{Source: src, TCView: r.x, Tenure: r.tenure, Epoch: r.e, Active: r.active, Result: res, Clamped: res != noClamp})
		}
	}
	addAfter("SYNC-10.4", []at{
		{8, 8, 0, false}, {8, 8, 0, true}, {9, 8, 0, true}, {15, 8, 0, true}, {16, 8, 0, true}, {7, 8, 0, true},
		{0, 8, 0, true}, {5, 1, 0, true}, {5, 0, 0, true}, {8, 8, 10, true}, {10, 8, 10, true}, {11, 8, 10, true},
		{17, 8, 10, true}, {100, 32, 0, true}, {math.MaxUint64 - 1, 8, 0, true}, {math.MaxUint64 - 3, 8, 0, true},
	})
	// gov5 must reproduce the SYNC §10.4 table's results.
	for i, want := range []uint64{9, 16, 16, 16, 24, 8, 8, 6, 6, 11, 11, 16, 21, 128, math.MaxUint64, math.MaxUint64 - 2} {
		if got := out.ViewAfter[i].Result; got != want {
			t.Fatalf("SYNC §10.4 row %d: view_after_tc(%d) = %d, spec %d", i, out.ViewAfter[i].TCView, got, want)
		}
	}
	var p1 []at
	for _, x := range []uint64{0, 1, 7, 8, 9, 15, 16, 191, 192, 193, 197, 198, 199, 200, 201, 202, 207, 208, 399, 400, 401} {
		p1 = append(p1, at{x, std.LeaderTenure, std.EpochLength, true})
	}
	addAfter("profile-1 standard genesis", p1)
	addAfter("V1 genesis_8s (T = 1)", []at{{0, p8.LeaderTenure, p8.EpochLength, true}, {57, p8.LeaderTenure, p8.EpochLength, true}, {10800, p8.LeaderTenure, p8.EpochLength, true}})
	addAfter("AM32", []at{{96, 8, 50, true}, {98, 8, 50, true}, {100, 8, 50, true}, {101, 8, 50, true}, {103, 8, 50, true}, {98, 8, 100, true}, {101, 8, 100, true}})
	addAfter("edge", []at{{0, 8, 10, true}, {1, 8, 10, true}, {math.MaxUint64, 8, 0, true}, {math.MaxUint64 - 8, 8, 0, true}, {math.MaxUint64 - 1, 1, 0, true}})
	for _, r := range out.ViewAfter {
		// x = 2^64-1 has no next view; gov5 returns x + 1 wrapped to 0.
		if r.Result <= r.TCView && r.TCView != math.MaxUint64 {
			t.Fatalf("view_after_tc(%d) = %d does not move forward", r.TCView, r.Result)
		}
	}

	// Sequences (n = 7, T = 8 unless stated).
	seq := func(id, desc string, n int, tenure, e uint64, dead map[uint32]uint64, start, stop uint64) v7Sequence {
		var ds []string
		for l := uint32(0); l < uint32(n); l++ {
			if from, ok := dead[l]; ok {
				ds = append(ds, fmt.Sprintf("L%d from view %d", l, from))
			}
		}
		return v7Sequence{ID: id, Description: desc, N: n, Tenure: tenure, EpochLength: e, Dead: ds, Steps: v7Run(n, tenure, e, dead, start, stop)}
	}
	out.Sequences = append(out.Sequences,
		seq("S1", "leader 1 dead", 7, 8, 0, map[uint32]uint64{1: 0}, 1, 25),
		seq("S2", "leaders 1 and 2 dead", 7, 8, 0, map[uint32]uint64{1: 0, 2: 0}, 7, 26),
		seq("S3", "leader 1 dies mid-tenure (silent from view 11)", 7, 8, 0, map[uint32]uint64{1: 11}, 7, 17),
		seq("S4", "timeout on the window's last view (leader 1 silent from view 15)", 7, 8, 0, map[uint32]uint64{1: 15}, 14, 17),
		seq("S5", "wrap-around: leader 6 dead", 7, 8, 0, map[uint32]uint64{6: 0}, 47, 58),
		seq("S7", "epoch clamp, E = 10: leader 1 dead", 7, 8, 10, map[uint32]uint64{1: 0}, 7, 17),
		seq("S9", "tenure 1, leader 3 dead", 7, 1, 0, map[uint32]uint64{3: 0}, 1, 12),
		seq("AM32", "rehearsal: L5 killed at view 98, E = 50: TC(98) clamps to boundary 101 (same leader), TC(101) -> 104", 7, 8, 50, map[uint32]uint64{5: 98}, 96, 106),
		seq("P1-std", "standard genesis (n = 4, T = 8, E = 200): leader 1 dead; its window 200..207 holds boundary 201: TC(200) clamps to 201 (same leader), TC(201) -> 208", std.Validators, std.LeaderTenure, std.EpochLength, map[uint32]uint64{1: 0}, 186, 210),
	)
	// S10: restart at view 16 after TC(8).
	out.Sequences = append(out.Sequences, v7Sequence{ID: "S10", Description: "restart: a node persisted at view 16 after TC(8) needs only the view",
		N: 7, Tenure: 8, Steps: []v7Step{{Event: "TC", View: 8, Leader: v7Leader(8, 7, 8), NextView: v7After(8, 8, 0, true), NextLeader: v7Leader(v7After(8, 8, 0, true), 7, 8)}}})
	// S11: QC(8) on some nodes, TC(8) on others; the nodes at 9 adopt TC(8).
	{
		tc := v7After(8, 8, 0, true)
		s11 := v7Sequence{ID: "S11", Description: "QC and TC for view 8 (race): nodes at 9 adopt the piggybacked TC(8) because view_after_tc(8) > 9; a node already at 16 ignores it",
			N: 7, Tenure: 8, Steps: []v7Step{
				{Event: "QC", View: 8, Leader: v7Leader(8, 7, 8), NextView: 9, NextLeader: v7Leader(9, 7, 8)},
				{Event: "TC", View: 8, Leader: v7Leader(8, 7, 8), NextView: tc, NextLeader: v7Leader(tc, 7, 8)},
			}}
		for _, cur := range []uint64{9, 16} {
			ev, next := "ignoreTC", cur
			if tc > cur {
				ev, next = "adoptTC", tc
			}
			s11.Steps = append(s11.Steps, v7Step{Event: ev, View: cur, Leader: v7Leader(cur, 7, 8), NextView: next, NextLeader: v7Leader(next, 7, 8)})
		}
		out.Sequences = append(out.Sequences, s11)
	}
	// Spot checks against SYNC §10.4 and AM32.
	check := func(id string, k int, view, next uint64, leader uint32) {
		for _, s := range out.Sequences {
			if s.ID != id {
				continue
			}
			st := s.Steps[k]
			if st.View != view || st.NextView != next || st.NextLeader != leader {
				t.Fatalf("%s step %d: %+v, want %d -> %d (L%d)", id, k, st, view, next, leader)
			}
			return
		}
		t.Fatalf("no sequence %s", id)
	}
	check("S1", 7, 8, 16, 2)
	check("S2", 2, 16, 24, 3)
	check("S3", 4, 11, 16, 2)
	check("S5", 1, 48, 56, 0)
	check("S7", 1, 8, 11, 1)
	check("S7", 2, 11, 16, 2)
	check("AM32", 2, 98, 101, 5)
	check("AM32", 3, 101, 104, 6)

	writeProfile1Vector(t, "V7", "leader_schedule.json", out)
	mirrorProfile1File(t, "V7", "README.md")
}

