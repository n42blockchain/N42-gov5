package main

import (
	"crypto/sha256"
	"encoding/binary"
	"errors"
	"math"

	"github.com/n42blockchain/N42/common/types"
	"github.com/n42blockchain/N42/internal/sharedexec"
)

const finitePhaseTargetNew = uint64(200000)

type boundedFiniteSchedule struct {
	PlanID               types.Hash                      `json:"plan_id"`
	Digest               types.Hash                      `json:"schedule_sha256"`
	TargetNew            uint64                          `json:"target_new_transactions"`
	NewlyAdmitted        uint64                          `json:"newly_admitted"`
	CanonicalSkipped     uint64                          `json:"canonical_skipped"`
	OriginalTransactions uint64                          `json:"original_transactions"`
	EncodedBytes         uint64                          `json:"encoded_bytes"`
	RetainedBytes        uint64                          `json:"retained_encoded_bytes"`
	FramesPerShard       []uint64                        `json:"frames_per_shard"`
	SenderNew            []uint64                        `json:"sender_new_transactions"`
	Frames               []sharedexec.BoundedResumeFrame `json:"frames"`
}

// Only schedule selection is generic for small fixtures. The public diagnostic
// fixes target=200000 and the existing production plan geometry. It never
// truncates an original frame or relaxes the owner's sealed full-prefix plan.
func selectBoundedFiniteSchedule(d sharedexec.CorpusDescriptor, p sharedexec.BoundedResumePlan, planID types.Hash, frames []sharedexec.BoundedResumeFrame, target uint64) (boundedFiniteSchedule, error) {
	fail := func() (boundedFiniteSchedule, error) {
		return boundedFiniteSchedule{}, errors.New("finite diagnostic original prefix/target differs")
	}
	if planID == (types.Hash{}) || target == 0 || target > finitePhaseTargetNew || p.CanonicalNonceSum > math.MaxUint64-target-499 {
		return fail()
	}
	digest, encoded, newly, err := sharedexec.BoundedResumeWhitelistID(d, p.Senders, p.NonceEndExclusive, frames)
	if err != nil || digest != p.WhitelistSHA256 || encoded != p.SourceEncodedBytes || newly != p.MaxNewTransactions || newly < target || uint64(len(frames)) != p.MaxSourceFrames {
		return fail()
	}
	var baseline uint64
	for _, sender := range p.Senders {
		if baseline > math.MaxUint64-sender.Nonce {
			return fail()
		}
		baseline += sender.Nonce
	}
	if baseline != p.CanonicalNonceSum || uint64(len(frames))*500 != p.MaxSourceTransactions || encoded > p.MaxSourceEncodedBytes {
		return fail()
	}
	byShard := make([][]sharedexec.BoundedResumeFrame, d.ShardCount)
	for _, f := range frames {
		byShard[f.ID.Shard] = append(byShard[f.ID.Shard], f)
	}
	out := boundedFiniteSchedule{PlanID: planID, TargetNew: target, FramesPerShard: make([]uint64, d.ShardCount), SenderNew: make([]uint64, len(p.Senders))}
	for sequence := uint64(0); ; sequence++ {
		progressed := false
		for shard := range byShard {
			if sequence >= uint64(len(byShard[shard])) {
				continue
			}
			progressed = true
			f := byShard[shard][sequence]
			out.Frames = append(out.Frames, f)
			out.FramesPerShard[shard]++
			out.NewlyAdmitted += uint64(f.NewlyAdmitted)
			out.CanonicalSkipped += uint64(f.CanonicalSkipped)
			out.OriginalTransactions += uint64(f.Transactions)
			out.EncodedBytes += sharedexec.CorpusWireHeaderSize + uint64(f.PayloadBytes)
			out.SenderNew[f.SenderIndex] += uint64(f.NewlyAdmitted)
			if f.NewlyAdmitted != 0 {
				out.RetainedBytes += uint64(f.PayloadBytes)
			}
			if out.OriginalTransactions > p.CanonicalNonceSum+target+499 {
				return fail()
			}
			if out.NewlyAdmitted >= target {
				if out.NewlyAdmitted > target+499 || out.OriginalTransactions != out.NewlyAdmitted+out.CanonicalSkipped {
					return fail()
				}
				out.Digest = boundedFiniteScheduleID(out)
				return out, nil
			}
		}
		if !progressed {
			return fail()
		}
	}
}

// A content digest for the finite diagnostic intent, not an arming capability.
// The complete source whitelist is independently regenerated by the owner.
func boundedFiniteScheduleID(s boundedFiniteSchedule) types.Hash {
	h := sha256.New()
	_, _ = h.Write([]byte("gov5/finite-phase-schedule/v1\x00"))
	_, _ = h.Write(s.PlanID[:])
	put := func(value any) { _ = binary.Write(h, binary.BigEndian, value) }
	put(s.TargetNew)
	put(uint64(len(s.Frames)))
	for _, f := range s.Frames {
		_, _ = h.Write(f.ID.CorpusID[:])
		put(f.ID.Shard)
		put(f.ID.Sequence)
		put(f.SenderIndex)
		_, _ = h.Write(f.Address[:])
		put(f.FirstNonce)
		put(f.Transactions)
		_, _ = h.Write(f.PayloadHash[:])
		put(f.PayloadBytes)
		put(f.CanonicalSkipped)
		put(f.NewlyAdmitted)
	}
	var digest types.Hash
	copy(digest[:], h.Sum(nil))
	return digest
}
